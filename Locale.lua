	_G["BINDING_HEADER_EXTRAITEMS_BAR" .. i] = EIB.L["Extra Items Bar"] .. " " .. i
	for j = 1, 12 do
		_G[format("BINDING_NAME_CLICK WTExtraItemsBar%dButton%d:LeftButton", i, j)] = EIB.L["Extra Items Bar"] .. " " .. i .. " " .. EIB.L["Button"] .. " " .. j
	end
end